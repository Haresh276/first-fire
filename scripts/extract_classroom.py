"""Rebuild the two NIST TN 1947 classroom traces from the original ZIP and XLSX."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
from xml.etree import ElementTree
from zipfile import ZipFile

ROOM_SHA = "a36111dc32fa3915c9ac5274ed9df38e964b65832230086294eb52131142666f"
SUMMARY_SHA = "7b5a958d4101cea4d73e0d22c9329c372d1f22d71e64e5c23bd304f1d61384d0"
SHEET = "Room I01-14"
XML = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
REL = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"


def check_hash(path, expected):
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise ValueError(f"Source SHA-256 differs for {path.name}")


def workbook_cells(path):
    with ZipFile(path) as workbook:
        book = ElementTree.fromstring(workbook.read("xl/workbook.xml"))
        sheet = next(s for s in book.iter(XML + "sheet") if s.get("name") == SHEET)
        rels = ElementTree.fromstring(workbook.read("xl/_rels/workbook.xml.rels"))
        part = next(r.get("Target") for r in rels if r.get("Id") == sheet.get(REL))
        doc = ElementTree.fromstring(workbook.read("xl/" + part))
        return {c.get("r"): c.findtext(XML + "v") for c in doc.iter(XML + "c")}


def extract(archive, summary):
    check_hash(archive, ROOM_SHA)
    check_hash(summary, SUMMARY_SHA)
    cells = workbook_cells(summary)
    runs = {}
    with ZipFile(archive) as bundle:
        for number, column in enumerate(("G", "H"), 1):
            filename = f"Room Data/FFoamG1T{number}.tsv"
            original = bundle.read(filename)
            reader = csv.DictReader(io.StringIO(original.decode()), delimiter="\t")
            rows = [[int(r["Counter (s)"]), float(r["Obsc (%/ft) smoothed"]), float(r["MIC (pA)"])] for r in reader]
            if any(b[0] != a[0] + 1 for a, b in zip(rows, rows[1:])):
                raise ValueError(f"Counter skipped or repeated in {filename}")
            runs[str(number)] = {
                "file": filename, "sha256": hashlib.sha256(original).hexdigest(),
                "cells": f"{column}6:{column}8", "column": column,
                "alarm": int(cells[column + "6"]),
                "obsc": round(float(cells[column + "7"]), 3),
                "mic": round(float(cells[column + "8"]), 3), "rows": rows,
            }
    return {"version": 1, "unit": "I01-6", "sheet": SHEET, "room_sha256": ROOM_SHA,
            "summary_sha256": SUMMARY_SHA, "runs": runs}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("summary", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "site" / "classroom-data.js")
    args = parser.parse_args()
    payload = extract(args.archive, args.summary)
    args.output.write_text("// Generated by scripts/extract_classroom.py from the NIST originals.\nwindow.FFClassroomData = "
                           + json.dumps(payload, separators=(",", ":")) + ";\n", encoding="utf-8")
