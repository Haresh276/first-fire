#!/usr/bin/env python3
"""Export browser inputs from FLINT 1.1 and the repository's PSI register.

Run with FLINT's Python dependencies installed, from any working directory.
The original rover report supplies every reference-case number. The exported
JANAF coefficients are SciPy's own polynomial representation used by FLINT.
"""
from dataclasses import asdict
from inspect import signature
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "flint-engine"))
from flint import chamber, thermo, rover
from flint.materials import LIBRARY

case = json.loads((ROOT / "flint-engine/results/rover/rover_case.json").read_text())
inventory = [asdict(item) for item in rover.default_inventory()]
fuel = {}
for item in inventory:
    key = item["material"]
    material = LIBRARY[key]
    substance = material.fuel
    fuel[key] = dict(name=material.name, pyrolysis=material.Tp, mw=substance.MW,
                     oxygen=substance.nu_O2, products=substance.products_per_mol(),
                     heat=substance.heat_of_combustion, cp=substance.cp_vap)
species = ["N2", "O2", "CO2", "H2O"]
case_settings = signature(chamber.cabin_fire).parameters
constants = dict(gas=thermo.R, psia=thermo.PSIA, ambient=thermo.Atmosphere.T,
                 mw=thermo.MW, co2_mask=rover.CO2_CREW_LIMIT,
                 hypoxia=rover.HYPOXIA_PO2_KPA, suit=rover.SUIT_KPA,
                 margin=signature(rover.flood_dose).parameters["margin"].default)
simulation = {key: case_settings[key].default for key in
              ["v_up_ref","v_lat_ratio","excess_ref","m_flux_ref","h_wall","chi_r","dt","t_max"]}
sources = json.loads((ROOT / "data/investigations.json").read_text())
payload = dict(reference=case, inventory=inventory, fuels=fuel, constants=constants,
               simulation=simulation, gravity=thermo.GRAVITY, knots=thermo._T.tolist(),
               enthalpy={key: thermo._HI[key].c.T.tolist() for key in species},
               investigations={s["accession"]: dict(name=s["name"], url="https://doi.org/"+s["doi"])
                   for s in sources if s["accession"] in {
                       "PSI-26","PSI-25","PSI-98","PSI-99","PSI-100","PSI-101",
                       "PSI-102","PSI-69","PSI-39","PSI-159"}})
target = ROOT / "site/rover-fire-data.js"
target.write_text("// Generated by scripts/export_rover_case.py from the supplied FLINT engine.\n"
                  + "globalThis.RoverFireData = " + json.dumps(payload, ensure_ascii=False, allow_nan=False,
                                                               separators=(",", ":")) + ";\n")
