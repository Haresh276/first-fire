// Rebuild the offline liquid-reservoir readout. No libraries, network or missions' data required.
const fs=require('node:fs');
const path=require('node:path');
const physics=require('../site/physics-lab.js');
function rng(seed) {
  let state=seed>>>0;
  return ()=>{state=(Math.imul(1664525,state)+1013904223)>>>0;return state/4294967296;};
}
const init=rng(72155), train=rng(664118), test=rng(920372);
const count=42;
const cells=Array.from({length:count},(_,index)=>({
  index,source:Math.floor(init()*count),input:Array.from({length:6},()=>6*(init()-.5)),
  bias:3*(init()-.5),feedback:2*(init()-.5),leak:0.006+.06*init(),
  gain:.02+.28*init(),reversal:2*init()-1
}));
const dim=physics.liquidInputs(physics.defaults).length+2+count;
const gram=Array.from({length:dim},()=>new Float64Array(dim));
const cross=new Float64Array(dim);
function scenario(random) {
  const s={...physics.defaults,fuel:random()<.5?'cellulose':'polyethylene'};
  for(const [key,[low,high]] of Object.entries(physics.trainingDomain)) s[key]=low+random()*(high-low);
  return s;
}
const trainCount=640, testCount=160;
for (let i=0;i<trainCount;i++){
  const s=scenario(train), inputs=physics.liquidInputs(s);
  let state=cells.map(()=>0);
  for(let t=physics.interval;t<=physics.horizon;t+=physics.interval){
    state=physics.liquidStep({cells},inputs,state,t);
    const features=[1,...inputs,t/physics.horizon,...state];
    const target=s.oxygen-physics.atTime(s,t).oxygen;
    features.forEach((v,j)=>{
      cross[j]+=v*target;
      for(let k=0;k<=j;k++) gram[j][k]+=v*features[k];
    });
  }
}
for(let i=0;i<dim;i++){
  gram[i][i]+=.0005;
  for(let j=0;j<i;j++)gram[j][i]=gram[i][j];
}
// Cholesky factorization and triangular solves for the ridge normal equations.
const l=Array.from({length:dim},()=>new Float64Array(dim));
for(let i=0;i<dim;i++)for(let j=0;j<=i;j++){
  let v=gram[i][j];
  for(let k=0;k<j;k++)v-=l[i][k]*l[j][k];
  l[i][j]=i===j?Math.sqrt(v):v/l[j][j];
}
const y=new Float64Array(dim), weights=Array(dim).fill(0);
for(let i=0;i<dim;i++){
  let v=cross[i]; for(let j=0;j<i;j++)v-=l[i][j]*y[j]; y[i]=v/l[i][i];
}
for(let i=dim-1;i>=0;i--){
  let v=y[i]; for(let j=i+1;j<dim;j++)v-=l[j][i]*weights[j]; weights[i]=v/l[i][i];
}
const model={cells,weights};
const errors=[],baseline=[];
for(let i=0;i<testCount;i++){
  const s=scenario(test),pred=physics.liquidPrediction(s,model);
  for(let point=1;point<pred.length;point++){
    const ref=physics.atTime(s,point*physics.interval).oxygen;
    errors.push(Math.abs(pred[point]-ref));
    baseline.push(Math.abs(s.oxygen-ref));
  }
}
errors.sort((a,b)=>a-b);
const mean=xs=>xs.reduce((p,n)=>p+n,0)/xs.length;
model.benchmark={trainRuns:trainCount,testRuns:testCount,points:errors.length,mae:mean(errors),p95:errors[Math.ceil(errors.length*.95)-1],worst:errors.at(-1),constantMae:mean(baseline),trainingSeed:664118,testSeed:920372};
const filename=path.join(__dirname,'../site/cabin-liquid-weights.js');
fs.writeFileSync(filename,'// Generated by scripts/train_cabin_liquid.cjs. Independent simulator runs only.\n'+
  'globalThis.FFCabinLiquid='+JSON.stringify(model)+';\n');
console.log(model.benchmark);
