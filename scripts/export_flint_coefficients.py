"""Export the supplied Python model's dry-gas lookup and published closure sensitivity."""
import json
import sys
from dataclasses import asdict, replace
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ROOT / 'flint-engine'
sys.path.insert(0, str(ENGINE))
from flint import data, limits, thermo
from flint.calibrate import closure_grid, validate
from flint.materials import LIBRARY
from flint.rover import PBuoyancy


def export():
    report = json.loads((ENGINE / 'results/core/results.json').read_text())
    buoy = PBuoyancy()
    gas = {
        'g': thermo.GRAVITY, 'psia': thermo.PSIA, 'R': thermo.R, 'sigma': thermo.SIGMA,
        'Tref': limits.T_REF, 'ambient': thermo.Atmosphere(1, 0).T,
        'Pref': limits.P_REF, 'k': thermo.k_gas(limits.T_REF),
        'cpO2': thermo.cp_species('O2', limits.T_REF), 'cpN2': thermo.cp_species('N2', limits.T_REF),
        'Xmin': limits.X_MIN, 'Xmax': limits.X_MAX, 'buoy': asdict(buoy),
        'nP': limits.LimitModel(LIBRARY['PMMA']).nP, 'Ch': report['Ch_all'], 'materials': {},
    }
    for key, cal in report['calibration'].items():
        material = LIBRARY[key]
        xs, ts = limits._tf_table(material)
        gas['materials'][key] = dict(label=material.name, lnK=cal['lnK'], Ea=material.E,
                                     Tp=material.Tp, eps=material.eps, tf=ts.tolist())
    gas['xs'] = xs.tolist()
    (ROOT/'site/flint-coefficients.js').write_text('// Generated by scripts/export_flint_coefficients.py\n'
            + 'globalThis.FLINTCoefficients = ' + json.dumps(gas, separators=(',', ':')) + ';\n')
    physics = {key: {world: [] for world in ('moon', 'mars')} for key in gas['materials']}
    for closure in closure_grid():
        fit = validate(closure)
        for key, model in fit.models.items():
            model = replace(model, Ch=fit.Ch_all)
            for world, values in physics[key].items():
                values.append(model.loc(limits.P_REF, closure.u_eff(0, thermo.GRAVITY[world])))
    alt = {key: data.ICES[key]['lunar_alt'] for key in physics}
    count = len(alt)
    sensitivity = {
        'source': 'FLINT 1.1 flint.calibrate.closure_grid + validate; flint.data.ICES',
        'pressure_psia': data.ICES_PRESSURE_PSIA, 'ranges': physics,
        'alternate_straight_line_mae_pts': sum(abs(row['straight_line_u0'] - alt[k])
                for k, row in report['lunar'].items()) * 100 / count,
        'alternate_uncorrected_mae_pts': sum(abs(row['one_g_60cms'] - alt[k])
                for k, row in report['lunar'].items()) * 100 / count,
        'material_labels': {key: LIBRARY[key].name for key in physics},
        'fm2': data.FM2,
    }
    (ROOT/'site/flint/closure-sensitivity.json').write_text(json.dumps(sensitivity, indent=2) + '\n')


if __name__ == '__main__':
    export()
